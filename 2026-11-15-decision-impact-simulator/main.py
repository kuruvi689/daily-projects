#!/usr/bin/env python3
"""Decision Impact Simulator (DIS)
A lightweight CLI that ingests competitor announcements (news URLs or text files),
extracts key strategic actions, scores their potential market impact, and outputs a concise report.
Designed for founders like Sivanesh to prioritize responses to competitor moves.

Features
--------
- Fetches article text via `requests` and `beautifulsoup4` (fallback to local file).
- Uses simple keyword‑based heuristics to detect action types (price change, product launch, partnership, funding, regulatory).
- Assigns an impact score (0‑100) based on action rarity and magnitude.
- Outputs a Markdown report suitable for newsletters or internal briefs.
- Core logic is modular for integration into larger SaaS pipelines.
"""

import argparse
import json
import sys
import re
from pathlib import Path
from typing import List, Dict, Tuple

# Optional external deps – keep imports optional for graceful fallback
try:
    import requests
    from bs4 import BeautifulSoup
except ImportError:  # pragma: no cover
    requests = None
    BeautifulSoup = None

# ---------------------------------------------------------------------------
# Heuristic dictionaries
# ---------------------------------------------------------------------------
ACTION_KEYWORDS = {
    "price": ["price cut", "discount", "sale", "price increase", "price hike"],
    "product": ["launch", "release", "introduce", "new model", "beta"],
    "partnership": ["partner", "collaboration", "joint venture", "ally"],
    "funding": ["raise", "funding round", "Series", "investment", "capital"],
    "regulatory": ["regulation", "compliance", "approval", "license", "policy"],
}
# Base impact weight per action type (0‑100)
BASE_IMPACT = {
    "price": 30,
    "product": 60,
    "partnership": 45,
    "funding": 55,
    "regulatory": 40,
}

# ---------------------------------------------------------------------------
# Utility functions
# ---------------------------------------------------------------------------
def fetch_url(url: str) -> str:
    """Return raw HTML text for *url* using requests.
    Raises RuntimeError on failure.
    """
    if not requests:
        raise RuntimeError("requests library is required for URL fetching")
    resp = requests.get(url, timeout=10)
    resp.raise_for_status()
    return resp.text

def extract_text(html: str) -> str:
    """Strip HTML tags and return readable text.
    Falls back to a simple regex if BeautifulSoup is unavailable.
    """
    if BeautifulSoup:
        soup = BeautifulSoup(html, "html.parser")
        # Remove script/style
        for tag in soup(["script", "style"]):
            tag.decompose()
        return soup.get_text(separator=" ", strip=True)
    # Very naive fallback
    text = re.sub(r"<[^>]+>", " ", html)
    return re.sub(r"\s+", " ", text).strip()

def load_source(path_or_url: str) -> str:
    """Load article text from a local file or remote URL.
    Returns plain text.
    """
    if path_or_url.startswith("http://") or path_or_url.startswith("https://"):
        html = fetch_url(path_or_url)
        return extract_text(html)
    else:
        p = Path(path_or_url)
        if not p.is_file():
            raise RuntimeError(f"File not found: {path_or_url}")
        return p.read_text(encoding="utf-8")

def detect_actions(text: str) -> List[Tuple[str, str]]:
    """Return a list of (action_type, matched_phrase) found in *text*.
    Simple case‑insensitive keyword search.
    """
    lowered = text.lower()
    found: List[Tuple[str, str]] = []
    for act, keywords in ACTION_KEYWORDS.items():
        for kw in keywords:
            if kw.lower() in lowered:
                found.append((act, kw))
                break  # one match per action type is enough
    return found

def score_actions(actions: List[Tuple[str, str]]) -> int:
    """Aggregate a single impact score (0‑100) from detected actions.
    Uses BASE_IMPACT weights; caps at 100.
    """
    total = 0
    for act, _ in actions:
        total += BASE_IMPACT.get(act, 0)
    return min(total, 100)

def generate_report(source: str, actions: List[Tuple[str, str]], score: int) -> str:
    """Create a markdown report.
    """
    title = f"## Competitor Impact Report for `{source}`\n"
    action_md = "\n".join([f"- **{act.title()}** detected (keyword: `{kw}`)" for act, kw in actions]) or "_No notable actions detected._"
    body = (
        f"{title}\n"
        f"**Impact Score:** {score}/100\n\n"
        f"**Detected Actions:**\n{action_md}\n\n"
        f"*Generated by **Decision Impact Simulator** – a lightweight strategic aid.*"
    )
    return body

# ---------------------------------------------------------------------------
# CLI entry point
# ---------------------------------------------------------------------------
def main(argv: List[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Simulate strategic impact of competitor announcements.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument("source", help="URL or local .txt/.html file containing the competitor announcement.")
    parser.add_argument(
        "-o",
        "--output",
        type=Path,
        default=Path("report.md"),
        help="Path to write the markdown report.",
    )
    parser.add_argument(
        "-j",
        "--json",
        action="store_true",
        help="Also emit a JSON summary to stdout.",
    )
    args = parser.parse_args(argv)

    try:
        raw_text = load_source(args.source)
    except Exception as exc:
        sys.stderr.write(f"Error loading source: {exc}\n")
        return 1

    actions = detect_actions(raw_text)
    score = score_actions(actions)
    report_md = generate_report(args.source, actions, score)
    args.output.write_text(report_md, encoding="utf-8")
    print(f"Report written to {args.output}")

    if args.json:
        summary = {
            "source": args.source,
            "impact_score": score,
            "actions": [{"type": a, "keyword": k} for a, k in actions],
        }
        json.dump(summary, sys.stdout, indent=2)
        print()  # newline after JSON
    return 0

if __name__ == "__main__":
    sys.exit(main())
