import argparse
import json
import os
import sys
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Tuple

DATA_DIR = Path.home() / ".decision_matrix"
DATA_FILE = DATA_DIR / "matrix.json"

def ensure_data_file() -> None:
    """Create storage directory and file if they don't exist."""
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    if not DATA_FILE.exists():
        with DATA_FILE.open("w", encoding="utf-8") as f:
            json.dump([], f)

def load_entries() -> List[Dict[str, Any]]:
    with DATA_FILE.open("r", encoding="utf-8") as f:
        return json.load(f)

def save_entries(entries: List[Dict[str, Any]]) -> None:
    with DATA_FILE.open("w", encoding="utf-8") as f:
        json.dump(entries, f, indent=2)

def add_entry(args: argparse.Namespace) -> None:
    """Add a new decision entry.
    The user supplies a title and a list of options. For each option they provide a comma
    separated list of scores for the criteria defined in the config (or defaults).
    Example:
      decision-matrix add "Launch new product" \
        --criteria Cost,Impact,Time \n        --options "OptionA" "OptionB" \n        --scores "5,8,3" "7,6,4"
    """
    criteria = [c.strip() for c in args.criteria.split(",")] if args.criteria else ["Cost", "Impact", "Time"]
    if len(args.options) != len(args.scores):
        print("Error: number of options and score sets must match.")
        sys.exit(1)
    option_data = []
    for opt, sc in zip(args.options, args.scores):
        scores = [float(s.strip()) for s in sc.split(",")]
        if len(scores) != len(criteria):
            print(f"Error: scores for '{opt}' must match number of criteria ({len(criteria)}).")
            sys.exit(1)
        option_data.append({"option": opt, "scores": scores})
    entry = {
        "id": datetime.utcnow().isoformat(),
        "title": args.title,
        "criteria": criteria,
        "options": option_data,
    }
    entries = load_entries()
    entries.append(entry)
    save_entries(entries)
    print(f"Entry added with ID {entry['id']}")

def list_entries(_: argparse.Namespace) -> None:
    entries = load_entries()
    if not entries:
        print("No decision entries found.")
        return
    for e in entries:
        print(f"ID: {e['id']} | Title: {e['title']}")

def show_entry(args: argparse.Namespace) -> None:
    entries = load_entries()
    entry = next((e for e in entries if e["id"] == args.id), None)
    if not entry:
        print(f"No entry with ID {args.id}")
        sys.exit(1)
    criteria = entry["criteria"]
    print(f"\nTitle: {entry['title']}")
    print("Criteria: " + ", ".join(criteria))
    print("\nOptions and Scores:")
    for opt in entry["options"]:
        scores_str = ", ".join(f"{c}:{s}" for c, s in zip(criteria, opt["scores"]))
        print(f"  - {opt['option']}: {scores_str}")
    # Compute weighted ranking (simple sum)
    totals = []
    for opt in entry["options"]:
        total = sum(opt["scores"])  # equal weight for all criteria
        totals.append((opt["option"], total))
    totals.sort(key=lambda x: x[1], reverse=True)
    print("\nRanking (higher total = better):")
    for rank, (opt_name, total) in enumerate(totals, start=1):
        print(f"  {rank}. {opt_name} (Score: {total})")

def delete_entry(args: argparse.Namespace) -> None:
    entries = load_entries()
    new_entries = [e for e in entries if e["id"] != args.id]
    if len(new_entries) == len(entries):
        print(f"No entry with ID {args.id} found.")
        return
    save_entries(new_entries)
    print(f"Entry {args.id} deleted.")

def export_entry(args: argparse.Namespace) -> None:
    entries = load_entries()
    entry = next((e for e in entries if e["id"] == args.id), None)
    if not entry:
        print(f"No entry with ID {args.id}")
        sys.exit(1)
    out_path = Path(args.output) if args.output else Path.cwd() / f"decision_{args.id}.md"
    with out_path.open("w", encoding="utf-8") as f:
        f.write(f"# Decision Matrix – {entry['title']}\n\n")
        f.write("## Criteria\n")
        for c in entry["criteria"]:
            f.write(f"- {c}\n")
        f.write("\n## Options\n")
        for opt in entry["options"]:
            scores = ", ".join(f"{c}:{s}" for c, s in zip(entry["criteria"], opt["scores"]))
            f.write(f"- **{opt['option']}** – {scores}\n")
        f.write("\n*Generated by decision-matrix-cli*\n")
    print(f"Exported to {out_path}")

def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="decision-matrix", description="Simple decision‑matrix CLI useful for product, finance, and strategic choices.")
    sub = parser.add_subparsers(dest="command", required=True)

    add = sub.add_parser("add", help="Add a new decision entry")
    add.add_argument("title", help="Descriptive title of the decision")
    add.add_argument("--criteria", help="Comma separated list of criteria (default: Cost,Impact,Time)")
    add.add_argument("--options", nargs="+", required=True, help="List of option names")
    add.add_argument("--scores", nargs="+", required=True, help="Comma separated scores matching criteria for each option")
    add.set_defaults(func=add_entry)

    sub.add_parser("list", help="List all saved decisions").set_defaults(func=list_entries)

    show = sub.add_parser("show", help="Show detailed matrix for a given ID")
    show.add_argument("id", help="ID of the decision entry")
    show.set_defaults(func=show_entry)

    delete = sub.add_parser("delete", help="Remove an entry by ID")
    delete.add_argument("id", help="ID to delete")
    delete.set_defaults(func=delete_entry)

    export = sub.add_parser("export", help="Export a matrix to Markdown")
    export.add_argument("id", help="ID of the entry to export")
    export.add_argument("--output", help="Destination file path (default: cwd/decision_<id>.md)")
    export.set_defaults(func=export_entry)

    return parser

def main() -> None:
    ensure_data_file()
    parser = build_parser()
    args = parser.parse_args()
    args.func(args)

if __name__ == "__main__":
    main()
